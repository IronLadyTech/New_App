# One-time: move heavy Android tooling off C: to D:\Android
# Run in PowerShell (Admin not required):
#   Set-Location C:\Users\Magvig\Desktop\app-new
#   .\scripts\migrate-android-to-d.ps1

$ErrorActionPreference = "Stop"
$root = "D:\Android"
$gradleDest = "$root\.gradle"
$gradleSrc = "$env:USERPROFILE\.gradle"
$sdkSrc = "$env:LOCALAPPDATA\Android\Sdk"
$sdkDest = "$root\Sdk"

New-Item -ItemType Directory -Force -Path $root, "$root\avd", "$root\temp", $gradleDest | Out-Null

function Set-UserEnv([string]$Name, [string]$Value) {
  [Environment]::SetEnvironmentVariable($Name, $Value, "User")
  Set-Item -Path "Env:$Name" -Value $Value
}

Set-UserEnv "GRADLE_USER_HOME" $gradleDest
Set-UserEnv "ANDROID_AVD_HOME" "$root\avd"
Set-UserEnv "ANDROID_USER_HOME" $root
Set-UserEnv "TEMP" "$root\temp"
Set-UserEnv "TMP" "$root\temp"

Write-Host "Stopping Gradle daemons (unlock C: cache) ..."
$gradlew = Join-Path $PSScriptRoot "..\android\gradlew.bat"
if (Test-Path $gradlew) {
  $prevGradle = $env:GRADLE_USER_HOME
  $env:GRADLE_USER_HOME = $gradleDest
  & $gradlew --stop 2>$null
  $env:GRADLE_USER_HOME = $prevGradle
}
Get-Process -Name "java" -ErrorAction SilentlyContinue | ForEach-Object {
  try {
    if ($_.Path -and ($_.Path -match "gradle|Gradle|android")) { Stop-Process -Id $_.Id -Force -ErrorAction Stop }
  } catch {}
}
Start-Sleep -Seconds 2

# Fresh Gradle on D: — delete partial moves and C: cache (re-download on next build)
foreach ($dir in @($gradleSrc, $gradleDest)) {
  if (Test-Path $dir) {
    Write-Host "Removing $dir ..."
    Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
    if (Test-Path $dir) {
      cmd /c "rd /s /q `"$dir`"" 2>$null
    }
  }
}
New-Item -ItemType Directory -Force -Path $gradleDest | Out-Null
Write-Host "Gradle will rebuild cache under $gradleDest"

# SDK stays on C: unless already on D: (moving is slow; Gradle+temp on D: is enough for builds)
if (Test-Path "$sdkDest\platform-tools") {
  Set-UserEnv "ANDROID_HOME" $sdkDest
  Set-UserEnv "ANDROID_SDK_ROOT" $sdkDest
  Write-Host "Using SDK on D: ($sdkDest)"
} elseif (Test-Path $sdkSrc) {
  Write-Host "SDK still on C: ($sdkSrc). To copy to D: later, run: robocopy ... (see script comments)"
} else {
  Write-Host "SDK not found at $sdkSrc"
}

$localProps = Join-Path $PSScriptRoot "..\android\local.properties"
$sdkDir = if (Test-Path "$sdkDest\platform-tools") { $sdkDest.Replace("\", "\\") } else { $sdkSrc.Replace("\", "\\") }
$content = "## Generated by migrate-android-to-d.ps1`nsdk.dir=$sdkDir`n"
Set-Content -Path $localProps -Value $content -Encoding UTF8
Write-Host "Wrote android\local.properties -> $sdkDir"

Write-Host ""
Write-Host "Done. Close and reopen terminals, then: npm run android"
